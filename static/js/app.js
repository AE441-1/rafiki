    function translateText(language) {
        currentLanguage = language;
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            const parent = node.parentElement;
            if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName) || parent.closest("[data-no-translate]")) continue;
            if (!originals.has(node)) originals.set(node, stripOuterQuotes(node.nodeValue));
            const original = originals.get(node);
            const phrase = normalize(original);
            const replacement = getTranslation(language, phrase);
            if (replacement !== node.nodeValue) {
                const leading = original.match(/^\s*/)?.[0] || "";
                const trailing = original.match(/\s*$/)?.[0] || "";
                node.nodeValue = `${leading}${replacement}${trailing}`;
            }
        }

        for (const element of document.querySelectorAll("[placeholder], [aria-label], [title]")) {
            for (const attribute of ["placeholder", "aria-label", "title"]) {
                if (!element.hasAttribute(attribute)) continue;
                const originalAttribute = `data-original-${attribute}`;
                if (!element.hasAttribute(originalAttribute)) element.setAttribute(originalAttribute, element.getAttribute(attribute));
                const source = element.getAttribute(originalAttribute);
                element.setAttribute(attribute, getTranslation(language, source));
            }
        }

        document.documentElement.lang = language;
        document.title = getTranslation(language, originalTitle);
        updateControls(language);
    }

